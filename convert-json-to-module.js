/**
 * Convert JSON to JavaScript Module
 * 
 * This script converts the toilet-data.json file to a JavaScript module
 * that can be loaded directly without a server.
 */

const fs = require('fs');
const path = require('path');

// Read the JSON file
const jsonFilePath = path.join(__dirname, 'toilet-data.json');
const outputFilePath = path.join(__dirname, 'toilet-data.js');

console.log(`Reading JSON file: ${jsonFilePath}`);

try {
    // Read the JSON file
    const jsonData = fs.readFileSync(jsonFilePath, 'utf8');
    
    // Parse the JSON to validate it
    const data = JSON.parse(jsonData);
    console.log(`Successfully parsed JSON with ${data.length} records`);
    
    // Create the JavaScript module content
    const moduleContent = `// This file was automatically generated from toilet-data.json
// Do not edit this file directly

export default ${JSON.stringify(data, null, 2)};
`;

    // Write the module file
    fs.writeFileSync(outputFilePath, moduleContent);
    console.log(`Successfully wrote module file: ${outputFilePath}`);
    
    console.log('Conversion complete!');
} catch (error) {
    console.error('Error converting JSON to module:', error);
} 